import type { ReactNode } from 'react';
import { Link } from 'react-router-dom';
import {
  AlertIcon,
  CheckIcon,
  DotFillIcon,
  GitBranchIcon,
  ShieldCheckIcon,
  XIcon,
} from '@primer/octicons-react';
import type { PullEvent, PullReason } from '@/lib/uiApi';
import { blocking, reasonText } from '@/lib/pullState';
import { timeAgo } from '@/lib/format';
import { PullStateLabel } from './PullStateLabel';

const num = (v: unknown) => (typeof v === 'number' ? v : null);
const str = (v: unknown) => (typeof v === 'string' && v ? v : null);

function Row({ icon, children }: { icon: ReactNode; children: ReactNode }) {
  return (
    <div className="TimelineItem ml-md-4 pl-md-3" style={{ marginLeft: 0 }}>
      <div className="TimelineItem-badge">{icon}</div>
      <div className="TimelineItem-body f6" style={{ minWidth: 0 }}>
        {children}
      </div>
    </div>
  );
}

/** One GitOrange timeline entry, inside the page's TimelineItem layout. `repoPath` is `/owner/name`. */
export function PullEventItem({
  e,
  repoPath,
}: {
  e: PullEvent;
  repoPath: string;
}) {
  const d = e.data ?? {};
  const pr = (n: number | null) =>
    n === null ? null : <Link to={`${repoPath}/pull/${n}`}>#{n}</Link>;
  const when = <span className="color-fg-muted"> {timeAgo(e.createdAt)}</span>;
  if (e.kind === 'state_changed' && e.state) {
    const reasons = ((d.reasons as PullReason[]) ?? []).filter(blocking);
    return (
      <div className="TimelineItem ml-md-4 pl-md-3" style={{ marginLeft: 0 }}>
        <div className="TimelineItem-badge">
          <DotFillIcon />
        </div>
        <div
          className="TimelineItem-body f6 d-flex flex-items-center flex-wrap"
          style={{ gap: 4 }}
        >
          <PullStateLabel state={{ state: e.state, reasons: [] }} />
          {reasons.length > 0 && (
            <span>{reasons.map(reasonText).join('; ')}</span>
          )}
          <span className="color-fg-muted">{timeAgo(e.createdAt)}</span>
        </div>
      </div>
    );
  }
  if (e.kind === 'stacked') {
    const branch = str(d.branch);
    return (
      <Row icon={<GitBranchIcon />}>
        Stacked on {pr(num(d.pr))}
        {branch && (
          <>
            {' '}
            (<code>{branch}</code>)
          </>
        )}
        {str(d.reason) && <>: {str(d.reason)}</>}
        {when}
      </Row>
    );
  }
  if (e.kind === 'unstacked') {
    const from = pr(num(d.pr));
    return (
      <Row icon={<GitBranchIcon />}>
        Unstacked{from && <> from {from}</>}
        {str(d.why) && <>: {str(d.why)}</>}
        {when}
      </Row>
    );
  }
  if (e.kind === 'ordered') {
    return (
      <Row icon={<GitBranchIcon />}>
        Lands after {pr(num(d.before))} so {pr(num(d.for_pr))} can build on both
        {when}
      </Row>
    );
  }
  if (e.kind === 'must_account_for') {
    const first = str(d.rebase_first);
    const instructions = str(d.instructions);
    return (
      <Row icon={<AlertIcon className="color-fg-attention" />}>
        Must account for {pr(num(d.pr))}
        {str(d.reason) && <>: {str(d.reason)}</>}
        {when}
        {first && (
          <div>
            Rebase onto <code>{first}</code> first.
          </div>
        )}
        {instructions && (
          <div className="mt-1 wb-break-word">
            {instructions}
            <div className="color-fg-muted">
              Generated by GitOrange; advisory.
            </div>
          </div>
        )}
      </Row>
    );
  }
  if (e.kind === 'accounted_for') {
    return (
      <Row icon={<CheckIcon className="color-fg-success" />}>
        Accounted for {pr(num(d.pr))}
        {str(d.reason) && <>: {str(d.reason)}</>}
        {when}
      </Row>
    );
  }
  if (e.kind === 'dismissed') {
    return (
      <Row icon={<XIcon />}>
        {e.actor ? <strong>{e.actor.username}</strong> : 'A maintainer'}{' '}
        dismissed the dependency on {pr(num(d.pr))}
        {when}
      </Row>
    );
  }
  if (e.kind === 'approved') {
    const over = Array.isArray(d.over)
      ? (d.over as PullReason[]).filter((r) => r && typeof r.kind === 'string')
      : [];
    return (
      <Row icon={<ShieldCheckIcon className="color-fg-success" />}>
        {e.actor ? <strong>{e.actor.username}</strong> : 'A former user'}
        {str(d.via) && <> via {str(d.via)}</>} approved{' '}
        <code>{(str(d.head_sha) ?? '').slice(0, 7)}</code>
        {over.length > 0 && <> over {over.map(reasonText).join('; ')}</>}
        {when}
      </Row>
    );
  }
  if (e.kind === 'withdrawn') {
    return (
      <Row icon={<XIcon />}>
        {e.actor ? <strong>{e.actor.username}</strong> : 'A former user'}{' '}
        withdrew their approval of{' '}
        <code>{(str(d.head_sha) ?? '').slice(0, 7)}</code>
        {when}
      </Row>
    );
  }
  return null;
}
