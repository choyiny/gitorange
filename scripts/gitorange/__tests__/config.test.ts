import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { parse, type ParseError } from 'jsonc-parser';
import { describe, expect, it } from 'vitest';
import {
  ConfigConflict,
  configHash,
  deployedPart,
  generateWranglerConfig,
  isGenerated,
} from '../config.ts';
import type { BuildPaths } from '../source.ts';
import { resourceNames } from '../names.ts';
import { newState, type InstallState } from '../state.ts';

const template = readFileSync(
  new URL('../../../wrangler.jsonc.example', import.meta.url),
  'utf8'
);

function fixture(hostname: string | null = 'git.example.com'): InstallState {
  const s = newState({
    installationId: 'acme-1a2b3c4d5e6f',
    accountId: 'a'.repeat(32),
    inputs: {
      name: 'acme',
      hostname,
      workersDev: hostname === null,
      fromEmail: 'noreply@example.com',
    },
    names: resourceNames('acme'),
    baseUrl: hostname ? `https://${hostname}` : 'https://acme.me.workers.dev',
  });
  s.resources.push({
    key: 'd1',
    kind: 'd1',
    name: 'acme-db',
    id: 'd1-uuid-1234',
    ownership: 'created',
    state: 'ready',
  });
  return s;
}

const ns = {
  JOB_RUNNER_NAMESPACE_ID: 'ns-job',
  LIVE_NAMESPACE_ID: 'ns-live',
};
const extra = {
  doNamespaceIds: ns,
  version: '1.2.3',
  existing: null,
  command: 'yarn gitorange install',
  build: null,
};

function read(text: string) {
  const errors: ParseError[] = [];
  const v = parse(text, errors) as Record<string, any>;
  expect(errors).toEqual([]);
  return v;
}

describe('generated marker', () => {
  it('old marker still counts as generated', () => {
    const old =
      '// Generated by yarn gitorange install (x). Edit inputs with yarn gitorange, not by hand.\n{}\n';
    expect(isGenerated(old)).toBe(true);
    expect(() =>
      generateWranglerConfig(template, fixture(), { ...extra, existing: old })
    ).not.toThrow(ConfigConflict);
  });
});

describe('generateWranglerConfig', () => {
  it('sets every field from the state', () => {
    const s = fixture();
    const text = generateWranglerConfig(template, s, extra);
    const c = read(text);
    expect(text.split('\n')[0]).toBe(
      '// Generated by gitorange (acme-1a2b3c4d5e6f). Edit inputs with yarn gitorange install, not by hand.'
    );
    expect(c.name).toBe('acme');
    expect(c.account_id).toBe(s.accountId);
    expect(c.d1_databases[0]).toMatchObject({
      database_name: 'acme-db',
      database_id: 'd1-uuid-1234',
    });
    expect(c.r2_buckets.map((b: any) => b.bucket_name)).toEqual([
      'acme-lfs',
      'acme-actions-logs',
      'acme-actions-cache',
    ]);
    expect(c.artifacts[0].namespace).toBe('acme');
    expect(c.workflows.map((w: any) => w.name)).toEqual([
      'acme-actions-run',
      'acme-merge-resolution',
    ]);
    expect(c.routes).toEqual([
      { pattern: 'git.example.com', custom_domain: true },
    ]);
    expect(c.vars).toMatchObject({
      BASE_URL: 'https://git.example.com',
      FROM_EMAIL: 'noreply@example.com',
      R2_ACCOUNT_ID: s.accountId,
      WORKER_NAME: 'acme',
      D1_DATABASE_ID: 'd1-uuid-1234',
      LFS_BUCKET_NAME: 'acme-lfs',
      ACTIONS_CACHE_BUCKET_NAME: 'acme-actions-cache',
      ACTIONS_LOGS_BUCKET_NAME: 'acme-actions-logs',
      ARTIFACTS_NAMESPACE: 'acme',
      ACTIONS_WORKFLOW_NAME: 'acme-actions-run',
      MERGE_RESOLUTION_WORKFLOW_NAME: 'acme-merge-resolution',
      JOB_RUNNER_NAMESPACE_ID: 'ns-job',
      MERGE_RESOLVER_NAMESPACE_ID: '',
      AGENT_REVIEWER_NAMESPACE_ID: '',
      LIVE_NAMESPACE_ID: 'ns-live',
      GITORANGE_VERSION: '1.2.3',
    });
    // template env block untouched
    expect(c.env.dev.vars.WORKER_NAME).toBe('gitorange-dev');
  });

  it('writes GITORANGE_INSTALLATION as a JSON string', () => {
    const s = fixture();
    const c = read(generateWranglerConfig(template, s, extra));
    expect(typeof c.vars.GITORANGE_INSTALLATION).toBe('string');
    expect(JSON.parse(c.vars.GITORANGE_INSTALLATION)).toEqual({
      installationId: s.installationId,
      ownershipNonce: s.ownershipNonce,
    });
  });

  it('kept vars override the template, and re-render to the same hash', () => {
    const s = fixture();
    s.inputs.vars = { APP_NAME: 'XY SPACE GitOrange', AI_GATEWAY: 'xy' };
    const a = generateWranglerConfig(template, s, extra);
    const v = read(a).vars;
    expect(v.APP_NAME).toBe('XY SPACE GitOrange');
    expect(v.AI_GATEWAY).toBe('xy');
    expect(v.REVIEW_MODEL).toBe(read(template).vars.REVIEW_MODEL);
    const b = generateWranglerConfig(template, s, { ...extra, existing: a });
    expect(configHash(b, null)).toBe(configHash(a, null));
    expect(configHash(a, null)).not.toBe(
      configHash(generateWranglerConfig(template, fixture(), extra), null)
    );
  });

  it('is byte-identical for the same inputs', () => {
    const s = fixture();
    expect(generateWranglerConfig(template, s, extra)).toBe(
      generateWranglerConfig(template, s, extra)
    );
  });

  it('workers.dev install has no routes and FROM_EMAIL may be empty', () => {
    const s = fixture(null);
    s.inputs.fromEmail = null;
    const c = read(generateWranglerConfig(template, s, extra));
    expect(c.routes).toBeUndefined();
    expect(c.vars.FROM_EMAIL).toBe('');
    expect(c.vars.BASE_URL).toBe('https://acme.me.workers.dev');
  });

  it('refuses a hand-written wrangler.jsonc', () => {
    expect(() =>
      generateWranglerConfig(template, fixture(), {
        ...extra,
        existing: '{ "name": "mine" }',
      })
    ).toThrow(ConfigConflict);
  });

  it('keeps the env block of an existing generated file', () => {
    const first = generateWranglerConfig(template, fixture(), extra);
    const edited = first.replace(
      '"WORKER_NAME": "gitorange-dev"',
      '"WORKER_NAME": "my-custom-dev"'
    );
    expect(edited).not.toBe(first);
    const c = read(
      generateWranglerConfig(template, fixture(), {
        ...extra,
        existing: edited,
      })
    );
    expect(c.env.dev.vars.WORKER_NAME).toBe('my-custom-dev');
  });

  it('keeps template comments below the header', () => {
    const text = generateWranglerConfig(template, fixture(), extra);
    expect(text).toContain(
      '// wrangler.jsonc is gitignored so each deployer keeps their own account and resource IDs.'
    );
    expect(text).toContain('// Git storage. One Artifacts repo per');
  });

  it('fails clearly when a binding is missing from the template', () => {
    expect(() =>
      generateWranglerConfig(
        template.replace('"binding": "LFS"', '"binding": "OTHER"'),
        fixture(),
        extra
      )
    ).toThrow(/binding "LFS"/);
  });
});

describe('isGenerated', () => {
  it('checks the first line', () => {
    expect(
      isGenerated(generateWranglerConfig(template, fixture(), extra))
    ).toBe(true);
    expect(isGenerated(template)).toBe(false);
    expect(isGenerated('\n// Generated by yarn gitorange install (x)')).toBe(
      false
    );
  });
});

function buildAt(root: string): BuildPaths {
  return {
    main: `${root}/worker/index.js`,
    assetsDir: `${root}/client`,
    migrationsDir: `${root}/migrations`,
    runnerDockerfile: `${root}/actions/runner/Dockerfile`,
    moduleConfig: {
      no_bundle: true,
      rules: [{ type: 'ESModule', globs: ['**/*.js'] }],
    },
  };
}

describe('package build paths', () => {
  it('package build paths are written', () => {
    const b = buildAt('/p');
    const c = read(
      generateWranglerConfig(template, fixture(), { ...extra, build: b })
    );
    const t = read(template);
    expect(c.main).toBe('/p/worker/index.js');
    expect(c.no_bundle).toBe(true);
    expect(c.rules).toEqual(b.moduleConfig.rules);
    expect(c.assets).toMatchObject({
      binding: 'ASSETS',
      directory: '/p/client',
    });
    for (const d of c.d1_databases)
      expect(d.migrations_dir).toBe('/p/migrations');
    expect(c.containers[0].images.runner.dockerfile).toBe(
      '/p/actions/runner/Dockerfile'
    );
    expect('env' in c).toBe(false);
    expect(c.exports).toEqual(t.exports);
    expect(c.durable_objects).toEqual(t.durable_objects);
  });

  it('package path change is not drift', () => {
    const state = fixture();
    const gen = (root: string, version = '1.2.3', command = 'x') =>
      generateWranglerConfig(template, state, {
        ...extra,
        version,
        command,
        build: buildAt(root),
      });
    const hash = (t: string, root: string) => configHash(t, buildAt(root));
    expect(hash(gen('/p'), '/p')).toBe(hash(gen('/q'), '/q'));
    expect(hash(gen('/p', '1.2.4'), '/p')).not.toBe(hash(gen('/p'), '/p'));
    expect(hash(gen('/p', '1.2.3', 'npx gitorange@2 install'), '/p')).toBe(
      hash(gen('/p'), '/p')
    );
  });

  it('checkout hash is the deployed part without the header line', () => {
    const text = generateWranglerConfig(template, fixture(), extra);
    const body = deployedPart(text).split('\n').slice(1).join('\n');
    expect(configHash(text, null)).toBe(
      createHash('sha256').update(body).digest('hex')
    );
    expect(configHash(text, null)).toBe(
      configHash(text.replace('yarn gitorange install', 'other'), null)
    );
  });
});
