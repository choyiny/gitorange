import {
  applyEdits,
  modify,
  parse,
  type FormattingOptions,
  type JSONPath,
} from 'jsonc-parser';
import { createHash } from 'node:crypto';
import type { BuildPaths } from './source.ts';
import type { InstallState } from './state.ts';

const MARKER = '// Generated by gitorange (';

/**
 * Vars an operator may tune: an adopted worker's values are kept (`inputs.vars`) over the
 * template's. Fresh installs never set them.
 */
export const TUNABLE_VARS: readonly string[] = [
  'APP_NAME',
  'AI_GATEWAY',
  'RESOLVER_MODEL',
  'SUMMARY_MODEL',
  'REVIEW_MODEL',
];
const OLD_MARKER = '// Generated by yarn gitorange install (';

const FORMAT: FormattingOptions = {
  insertSpaces: true,
  tabSize: 2,
  eol: '\n',
};

export class ConfigConflict extends Error {
  /** `path`: the file as named to the person (default: `wrangler.jsonc` in the current directory). */
  constructor(path = 'wrangler.jsonc') {
    super(
      `${path} exists and was not generated by gitorange. Move it aside (e.g. \`mv ${path} ${path}.hand\`) and run the command again. Nothing was changed.`
    );
    this.name = 'ConfigConflict';
  }
}

export function isGenerated(text: string): boolean {
  const first = text.split('\n', 1)[0].replace(/\r$/, '');
  return first.startsWith(MARKER) || first.startsWith(OLD_MARKER);
}

function parseConfig(text: string): Record<string, unknown> {
  const errors: unknown[] = [];
  const value = parse(text, errors as never[], { allowTrailingComma: true });
  if (errors.length > 0 || value === null || typeof value !== 'object') {
    throw new Error('wrangler.jsonc could not be parsed as JSONC.');
  }
  return value as Record<string, unknown>;
}

/**
 * Builds wrangler.jsonc from the tracked template and the install state.
 * Pure: the output depends only on the arguments. Comments in the template
 * survive because every change is a targeted jsonc-parser edit.
 */
export function generateWranglerConfig(
  template: string,
  s: InstallState,
  extra: {
    doNamespaceIds: Record<string, string>;
    version: string;
    existing: string | null;
    /** The printed install command named in the header. */
    command: string;
    /** Package install: absolute paths into the package, and no dev environment. Checkout: null. */
    build: BuildPaths | null;
  }
): string {
  if (extra.existing !== null && !isGenerated(extra.existing)) {
    throw new ConfigConflict();
  }

  let text = template.replace(/\r\n/g, '\n');
  const set = (path: JSONPath, value: unknown, insertAfter?: string) => {
    text = applyEdits(
      text,
      modify(text, path, value, {
        formattingOptions: FORMAT,
        getInsertionIndex:
          insertAfter === undefined
            ? undefined
            : (props) => props.indexOf(insertAfter) + 1,
      })
    );
  };

  const root = parseConfig(text);
  const indexOf = (key: string, binding: string): number => {
    const list = root[key];
    const i = Array.isArray(list)
      ? list.findIndex((e) => (e as { binding?: string })?.binding === binding)
      : -1;
    if (i < 0) {
      throw new Error(
        `wrangler.jsonc.example has no ${key} entry with binding "${binding}".`
      );
    }
    return i;
  };

  const n = s.names;
  const d1 = s.resources.find((r) => r.key === 'd1');
  if (!d1) throw new Error('The install state has no d1 resource.');

  set(['name'], n.worker);
  set(['account_id'], s.accountId);

  const db = indexOf('d1_databases', 'DB');
  set(['d1_databases', db, 'database_name'], n.d1);
  set(['d1_databases', db, 'database_id'], d1.id);

  set(['r2_buckets', indexOf('r2_buckets', 'LFS'), 'bucket_name'], n.lfs);
  set(
    ['r2_buckets', indexOf('r2_buckets', 'ACTIONS_LOGS'), 'bucket_name'],
    n.actionsLogs
  );
  set(
    ['r2_buckets', indexOf('r2_buckets', 'ACTIONS_CACHE'), 'bucket_name'],
    n.actionsCache
  );
  set(
    ['artifacts', indexOf('artifacts', 'ARTIFACTS'), 'namespace'],
    n.artifacts
  );
  set(
    ['workflows', indexOf('workflows', 'ACTIONS_RUN'), 'name'],
    n.actionsWorkflow
  );
  set(
    ['workflows', indexOf('workflows', 'MERGE_RESOLUTION'), 'name'],
    n.mergeWorkflow
  );

  if (s.inputs.hostname) {
    set(
      ['routes'],
      [{ pattern: s.inputs.hostname, custom_domain: true }],
      'compatibility_flags'
    );
  } else if ('routes' in root) {
    set(['routes'], undefined);
  }

  const vars: Record<string, string> = {
    BASE_URL: s.baseUrl,
    FROM_EMAIL: s.inputs.fromEmail ?? '',
    R2_ACCOUNT_ID: s.accountId,
    WORKER_NAME: n.worker,
    D1_DATABASE_ID: d1.id,
    LFS_BUCKET_NAME: n.lfs,
    ACTIONS_CACHE_BUCKET_NAME: n.actionsCache,
    ACTIONS_LOGS_BUCKET_NAME: n.actionsLogs,
    ARTIFACTS_NAMESPACE: n.artifacts,
    ACTIONS_WORKFLOW_NAME: n.actionsWorkflow,
    MERGE_RESOLUTION_WORKFLOW_NAME: n.mergeWorkflow,
    // A string on purpose: wrangler uploads object vars as `json` bindings and
    // the installer reads this back through `plain_text` bindings only.
    GITORANGE_INSTALLATION: JSON.stringify({
      installationId: s.installationId,
      ownershipNonce: s.ownershipNonce,
    }),
    GITORANGE_VERSION: extra.version,
  };
  for (const v of [
    'JOB_RUNNER_NAMESPACE_ID',
    'MERGE_RESOLVER_NAMESPACE_ID',
    'AGENT_REVIEWER_NAMESPACE_ID',
    'LIVE_NAMESPACE_ID',
  ]) {
    vars[v] = extra.doNamespaceIds[v] ?? '';
  }
  for (const k of TUNABLE_VARS) {
    const kept = s.inputs.vars?.[k];
    if (kept !== undefined) vars[k] = kept;
  }
  for (const [k, v] of Object.entries(vars)) set(['vars', k], v);

  if (extra.build) {
    const b = extra.build;
    set(['main'], b.main);
    for (const [k, v] of Object.entries(b.moduleConfig)) set([k], v);
    set(['assets', 'directory'], b.assetsDir);
    const dbs = parseConfig(text).d1_databases as unknown[];
    dbs.forEach((_, i) =>
      set(['d1_databases', i, 'migrations_dir'], b.migrationsDir)
    );
    set(
      ['containers', 0, 'images', 'runner', 'dockerfile'],
      b.runnerDockerfile
    );
    // The dev environment is for working on a checkout; a package has nothing to run it with.
    if ('env' in parseConfig(text)) set(['env'], undefined);
  } else if (extra.existing !== null) {
    const env = parseConfig(extra.existing).env;
    if (env !== undefined) set(['env'], env);
  }

  const header = `${MARKER}${s.installationId}). Edit inputs with ${extra.command}, not by hand.`;
  return `${header}\n${text}`;
}

/**
 * The text that drift detection hashes: the generated config without its `env` block. A plain
 * `wrangler deploy` (yarn deploy) deploys only the top level, so editing `env.dev` is not drift.
 */
export function deployedPart(text: string): string {
  return applyEdits(
    text,
    modify(text, ['env'], undefined, { formattingOptions: FORMAT })
  );
}

const PACKAGE_PATH = '<package>';

/**
 * sha256 of the deployed part, without the generated header line (so a changed header or printed
 * command is not drift). With `build` (package install) the install-location paths (`main`,
 * `assets.directory`, every `migrations_dir`, the runner `dockerfile`) are replaced by a literal
 * first, so moving or upgrading the package directory is not drift either.
 */
export function configHash(text: string, build: BuildPaths | null): string {
  let part = deployedPart(text);
  const first = part.split('\n', 1)[0].replace(/\r$/, '');
  if (first.startsWith(MARKER) || first.startsWith(OLD_MARKER)) {
    part = part.slice(part.indexOf('\n') + 1);
  }
  if (build) {
    const root = parseConfig(part);
    const set = (path: JSONPath) => {
      part = applyEdits(
        part,
        modify(part, path, PACKAGE_PATH, { formattingOptions: FORMAT })
      );
    };
    if ('main' in root) set(['main']);
    const assets = root.assets as { directory?: unknown } | undefined;
    if (assets && 'directory' in assets) set(['assets', 'directory']);
    if (Array.isArray(root.d1_databases)) {
      root.d1_databases.forEach((d, i) => {
        if (d && typeof d === 'object' && 'migrations_dir' in d)
          set(['d1_databases', i, 'migrations_dir']);
      });
    }
    const runner = (
      root.containers as { images?: { runner?: { dockerfile?: unknown } } }[]
    )?.[0]?.images?.runner;
    if (runner && 'dockerfile' in runner)
      set(['containers', 0, 'images', 'runner', 'dockerfile']);
  }
  return createHash('sha256').update(part).digest('hex');
}
