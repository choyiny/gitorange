#!/usr/bin/env node
// PreToolUse (Write|Edit): deny writes to generated/protected files.
// Config: protected: [{ pattern, reason }]
import { readHookInput, loadConfig, matchesGlob, denyPreToolUse, targetFile } from "./_lib.mjs";

const input = await readHookInput();
const file = targetFile(input);
if (!file) process.exit(0);

const configured = loadConfig().protected;
const patterns = Array.isArray(configured) ? configured : [];
for (const entry of patterns) {
  // A bare string (e.g. `"protected": ["**/*.gen.ts"]`) is a plausible hand-edit — accept it as a
  // pattern with a default reason rather than silently guarding nothing.
  const pattern = typeof entry === "string" ? entry : entry?.pattern;
  const reason = typeof entry === "string" ? undefined : entry?.reason;
  if (typeof pattern !== "string" || !pattern || !matchesGlob(file, pattern)) continue;
  denyPreToolUse(
    `Blocked: ${file} is a protected, generated file.\n\n` +
      `${reason ?? "Do not edit this file by hand."}\n\n` +
      `If you believe this file genuinely must be hand-edited, stop and ask the user. ` +
      `Do not work around this hook.`,
  );
}

process.exit(0);
